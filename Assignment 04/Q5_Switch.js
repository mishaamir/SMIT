// Q5 - Menu Selection Using Switch

let choice = 2;

switch (choice) {
    case 1:
        console.log("You selected Home");
        break;

    case 2:
        console.log("You selected About");
        break;

    case 3:
        console.log("You selected Services");
        break;

    case 4:
        console.log("You selected Contact");
        break;

    default:
        console.log("Invalid Choice");
}