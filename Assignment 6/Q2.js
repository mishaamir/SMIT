let students= ["Sara", "Ali", "Zara", "Sana", "Ahmed"];

// Array Push
console.log(students.push("Hamza"));
console.log("After Push", students); 

// Array Pop
console.log(students.pop());
console.log("After Pop", students);

// Array Unshift
console.log(students.unshift("Zainab"));
console.log("After Unshift", students);

// Array Shift
console.log(students.shift());
console.log("After Shift", students);

// Array Length
console.log("Student Length", students.length);