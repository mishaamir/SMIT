// String is used to text
var name = "Sara";

// Number is used to text numbers
let age = 18;

// Boolean is used to text true or false
let isStudent = true;

// Undefined means no value has been yet
let nickname;

// Null means the value is empty
let middleName = null;

// Object stores related info together
const address = {
  city: "Karachi",
  country: "Pakistan",
};

// Array stores multiple values in one variable
let hobbies = ["Painting", "Coding", "Reading"];

// Symbol is used to create a unique value
let id = Symbol("personID");

// BigInt is used for very large numbers
let phoneNumber = 923001234567n;

console.log(name);
console.log(typeof name);

console.log(age);
console.log(typeof age);

console.log(isStudent);
